def config_for(split: str, size: str, types: list) -> dict:
    return {"dataset_profile": split, "company_size": size, "enabled_issue_types": list(types), "max_steps": 100,
            "time_limit_seconds": 60, "evaluation_mode": "open"}


def _require_public_key() -> None:
    if os.environ.get("GENESIS_EPISODE_KEY", PUBLIC_DEFAULT_KEY) != PUBLIC_DEFAULT_KEY:
        raise SystemExit("open datasets use the public episode key: unset GENESIS_EPISODE_KEY")


def summarize(ep) -> dict:
    m = ep.manifest
    return {
        "base_currency": m["base_currency"],
        "currencies": sorted(m["currency_decimals"]),
        "timezone": m["timezone"],
        "period_start": m["period_start"],
        "record_counts": m["record_counts"],
        "document_count": m["document_count"],
        "n_issues": len(ep.truth["issues"]),
        "issue_types": dict(sorted(_types(ep).items())),
        "targets": {t: sorted(_targets(ep, t)) for t in (FX, PERIOD) if _targets(ep, t)},
        "scenarios": dict(sorted(_scen(ep).items())),
    }


# ----------------------------------------------------------------------------- select

def select(split: str) -> dict:
    _require_public_key()
    used = set()
    entries = []
    for name, size, types, pred, desc in SLOTS[split]:
        cfg = config_for(split, size, types)
        for seed in range(SEARCH_START[split], SEARCH_START[split] + SEARCH_LIMIT):
            if seed in used:
                continue
            plan = derive_plan(seed, validate_config(cfg))
            ep = generate(seed, cfg)
            if pred(plan, ep) and verify_episode(ep)["ok"]:
                used.add(seed)
                entries.append({"slot": name, "description": desc, "seed": seed, "config": cfg,
                                "episode_id": ep.episode_id, "summary": summarize(ep)})
                break
        else:
            raise RuntimeError(f"no seed found for slot {split}/{name}")
    return {"environment_version": ENVIRONMENT_VERSION, "split": split,
            "selection": f"first seed from {SEARCH_START[split]} satisfying each slot (auditgym/dataset.py)",
            "episodes": entries}


def load_manifest(split: str, root: Path = DATASETS) -> dict:
    return json.loads((root / f"{split}.json").read_text(encoding="utf-8"))


# ----------------------------------------------------------------------------- build

def build(split: str, out: Path, with_private: bool = False) -> list:
    _require_public_key()
    paths = []
    for e in load_manifest(split)["episodes"]:
        ep = generate(e["seed"], e["config"])
        d = Path(out) / split / ep.episode_id
        if with_private:
            write_episode(ep, d)
        else:
            for rel, text in render_files(ep).items():
                if rel.startswith("public/"):
                    p = d / rel
                    p.parent.mkdir(parents=True, exist_ok=True)
                    p.write_bytes(text.encode("utf-8"))
        paths.append(d)
    return paths


# ----------------------------------------------------------------------------- check

def coverage_problems(manifests: dict) -> list:
    """Diversity criteria over the open sets."""
    probs = []
    eps = {s: manifests[s]["episodes"] for s in SPLITS}
    every = [e for s in SPLITS for e in eps[s]]
    seeds = {s: {e["seed"] for e in eps[s]} for s in SPLITS}
    if any(len(eps[s]) != 10 for s in SPLITS):
        probs.append("each split must have exactly 10 episodes")
    if seeds["train"] & seeds["dev"]:
        probs.append("train and dev seeds overlap")
    if len({e["episode_id"] for e in every}) != len(every):
        probs.append("episode ids are not unique")
    for s in SPLITS:
        S = [e["summary"] for e in eps[s]]
        if any(e["config"]["dataset_profile"] != s for e in eps[s]):
            probs.append(f"{s}: dataset_profile must equal the split")
        if sum(1 for x in S if x["n_issues"] == 0) < 2:
            probs.append(f"{s}: at least 2 clean companies")
        if sum(1 for x in S if x["scenarios"]) < 3:
            probs.append(f"{s}: at least 3 episodes with interacting errors")
        if {e["config"]["company_size"] for e in eps[s]} != {"small", "medium", "large"}:
            probs.append(f"{s}: all three company sizes")
        if {t for x in S for t in x["issue_types"]} != set(ISSUE_TYPES):
            probs.append(f"{s}: every issue type at least once")
        if {k for x in S for k in x["scenarios"]} != {"fx_invoice_partial", "boundary_payment_fx_partial"}:
            probs.append(f"{s}: both interacting scenarios")
    S = [e["summary"] for e in every]
    per_type = collections.Counter()
    for x in S:
        per_type.update(x["issue_types"])
    for t in ISSUE_TYPES:
        if per_type[t] < 4:
            probs.append(f"issue type {t} appears fewer than 4 times overall")
    for t in (FX, PERIOD):
        if {g for x in S for g in x["targets"].get(t, [])} != {"invoice", "payment"}:
            probs.append(f"{t}: both invoice and payment targets overall")
    if len({x["base_currency"] for x in S}) < 2:
        probs.append("at least 2 base currencies")
    if len({x["timezone"] for x in S}) < 4:
        probs.append("at least 4 timezones")
    signs = {x["period_start"][-6] for x in S if x["scenarios"].get("boundary_payment_fx_partial")}
    if signs != {"+", "-"}:
        probs.append("boundary scenario must cover both UTC offset signs")
    for x in S:
        rc = x["record_counts"]
        if not (200 <= rc["ledger"] <= 2000 and 20 <= x["document_count"] <= 200 and x["n_issues"] <= 12):
            probs.append("episode outside the case size limits")
    return probs


def check(root: Path = ROOT) -> list:
    """Regenerate every open episode and compare with the committed public files."""
    _require_public_key()
    probs = []
    manifests = {s: load_manifest(s, root / "datasets") for s in SPLITS}
    slots = {s: {name: pred for name, _, _, pred, _ in SLOTS[s]} for s in SPLITS}
    for s in SPLITS:
        committed = {p.name for p in (root / "episodes" / s).iterdir() if p.is_dir()} if (root / "episodes" / s).exists() else set()
        expected = {e["episode_id"] for e in manifests[s]["episodes"]}
        if committed != expected:
            probs.append(f"{s}: committed episode dirs differ from datasets/{s}.json")
        for e in manifests[s]["episodes"]:
            ep = generate(e["seed"], e["config"])
            tag = f"{s}/{e['slot']}"
            if ep.episode_id != e["episode_id"]:
                probs.append(f"{tag}: episode_id changed (generator drift?)")
                continue
            if summarize(ep) != e["summary"]:
                probs.append(f"{tag}: summary changed")
            if not slots[s][e["slot"]](derive_plan(e["seed"], validate_config(e["config"])), ep):
                probs.append(f"{tag}: episode no longer satisfies its slot")
            res = verify_episode(ep)
            if not res["ok"]:
                probs.append(f"{tag}: verification failed {[k for k, v in res['errors'].items() if v]}")
            d = root / "episodes" / s / ep.episode_id
            files = render_files(ep)
            if d.exists():
                on_disk = {p.relative_to(d).as_posix() for p in d.rglob("*") if p.is_file()}
                if on_disk != {f"public/{n}" for n in PUBLIC_FILES}:
                    probs.append(f"{tag}: committed files must be exactly the public set")
                for name in PUBLIC_FILES:
                    p = d / "public" / name
                    if p.exists() and p.read_bytes() != files[f"public/{name}"].encode("utf-8"):
                        probs.append(f"{tag}: public/{name} differs from regeneration")
    probs += coverage_problems(manifests)
    return probs


def report_markdown(manifests: dict) -> str:
    lines = ["| Набор | Слот | Seed | Размер | База | Часовой пояс | Проводок | Документов | Ошибок | Типы | Сценарии |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    short = {DUP: "dup", ALLOC: "alloc", FX: "fx", PERIOD: "period"}
    for s in SPLITS:
        for e in manifests[s]["episodes"]:
            x = e["summary"]
            types = ", ".join(f"{short[t]}×{n}" for t, n in x["issue_types"].items()) or "—"
            scen = ", ".join(x["scenarios"]) or "—"
            lines.append(f"| {s} | `{e['slot']}` | {e['seed']} | {e['config']['company_size']} | {x['base_currency']} | "
                         f"{x['timezone']} ({x['period_start'][-6:]}) | {x['record_counts']['ledger']} | "
                         f"{x['document_count']} | {x['n_issues']} | {types} | {scen} |")
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m auditgym.dataset")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("select")
    b = sub.add_parser("build")
    b.add_argument("--out", default=str(EPISODES))
    b.add_argument("--with-private", action="store_true")
    sub.add_parser("check")
    sub.add_parser("report")
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to a legacy code page
    if a.cmd == "select":
        DATASETS.mkdir(exist_ok=True)
        for s in SPLITS:
            m = select(s)
            (DATASETS / f"{s}.json").write_bytes((json.dumps(m, indent=2, ensure_ascii=False) + "\n").encode("utf-8"))
            print(f"{s}: seeds {[e['seed'] for e in m['episodes']]}")
    elif a.cmd == "build":
        if a.with_private and Path(a.out).resolve() == EPISODES.resolve():
            raise SystemExit("private files must not be written into the repository; pass --out elsewhere")
        for s in SPLITS:
            print(f"{s}: {len(build(s, Path(a.out), a.with_private))} episodes -> {Path(a.out) / s}")
    elif a.cmd == "report":
        print(report_markdown({s: load_manifest(s) for s in SPLITS}))
    else:
        probs = check()
        for p in probs:
            print("FAIL", p)
        print("dataset check: ok" if not probs else f"dataset check: {len(probs)} problem(s)")
        return 1 if probs else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
