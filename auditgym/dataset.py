from .version import ENVIRONMENT_VERSION

ROOT = Path(__file__).resolve().parent.parent
DATASETS = ROOT / "datasets"
EPISODES = ROOT / "episodes"
SPLITS = ("train", "dev")
SEARCH_START = {"train": 1000, "dev": 2000}
SEARCH_LIMIT = 4000

ALL = list(ISSUE_TYPES)
DUP, ALLOC, FX, PERIOD = ISSUE_TYPES


def _types(ep) -> collections.Counter:
    return collections.Counter(i["type"] for i in ep.truth["issues"])


def _targets(ep, t) -> set:
    return {i["target"] for i in ep.truth["issues"] if i["type"] == t}


def _scen(ep) -> collections.Counter:
    return collections.Counter(i["scenario"] for i in ep.truth["issues"] if i["scenario"])


def _sign(ep) -> str:
    return ep.manifest["period_start"][-6]


