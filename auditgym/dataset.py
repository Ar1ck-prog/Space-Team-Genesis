"""Open train/dev episode sets (issue #8): slot-based selection, build and diversity checks.

Each split has 10 *slots* (what the episode must contain). Selection searches seeds
deterministically from a split-specific start and keeps the first seed whose episode, built
with the public API `generate(seed, config)`, satisfies the slot. The chosen seeds are pinned
in datasets/<split>.json, so the environment's reset(seed, config) reproduces the same books.

  python -m auditgym.dataset select     # (re)write datasets/*.json  (only when slots change)
  python -m auditgym.dataset build      # write episodes/<split>/<episode_id>/public/
  python -m auditgym.dataset build --with-private --out /tmp/eps   # + truth/provenance, trusted use only
  python -m auditgym.dataset check      # regenerate, compare with committed files, verify diversity

Only public files are committed. Train/dev seeds are public, so their truth can always be
regenerated by trusted code; it is not stored in the repository.
"""

from __future__ import annotations

